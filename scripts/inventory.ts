import { writeFileSync } from "node:fs";
import { ROWS } from "../content/inventory";
import { eq, show } from "../lib/frac";
import { CLUSTERS, DOMAINS } from "../lib/types";
import { EXERCISES } from "../content";

let bad = 0;
const fails: string[] = [];
for (const r of ROWS) {
  if (r.compute && r.statedValues) {
    const got = r.compute();
    const sameLen = got.length === r.statedValues.length;
    if (!sameLen || got.some((g, i) => !eq(g, r.statedValues![i]))) {
      bad++;
      fails.push(`${r.id}: computed [${got.map((g) => show(g)).join(", ")}] vs stated [${r.statedValues.map((g) => show(g)).join(", ")}]`);
    }
    if (r.printed && (r.printed.length !== got.length || r.printed.some((p, i) => !eq(p, got[i])))) {
      bad++;
      fails.push(`${r.id}: computed [${got.map((g) => show(g)).join(", ")}] vs PRINTED [${r.printed.map((g) => show(g)).join(", ")}]`);
    }
  }
}
// The printed answer banks (p.14, p.26) as a multiset must equal what we computed.
const bank14 = [9, 77, 504, 72, 225, 260, 171, 33, 60, 35, 400, 32, 130, 680, 15].sort((a, b) => a - b).join();
const ours14 = ROWS.filter((r) => r.id.startsWith("ir-8-")).map((r) => Number(r.compute!()[0].n)).sort((a, b) => a - b).join();
const bank26 = [27, 196, 2, 18, 126, 99, 127, 86, 109, 4102, 87, 6561].sort((a, b) => a - b).join();
const ours26 = ROWS.filter((r) => r.id.startsWith("ir-18-")).map((r) => Number(r.compute!()[0].n)).sort((a, b) => a - b).join();
if (bank14 !== ours14) { bad++; fails.push(`p.14 answer bank mismatch: ${ours14}`); }
if (bank26 !== ours26) { bad++; fails.push(`p.26 answer bank mismatch: ${ours26}`); }

// reflect what was actually built: status and final section come from the exercise
for (const r of ROWS) {
  const ex = EXERCISES.find((e) => e.id === r.id);
  if (!ex) continue;
  const b = ex.build(ex.base);
  (r as any).status = b.reflection ? "reflection" : "built";
  r.cluster = ex.cluster;
  (r as any).diagram = b.diagram ? (b.diagram.kind === "table" ? "table" : "figure") : "";
}
const counted = ROWS.filter((r) => r.status !== "duplicate");
const numeric = ROWS.filter((r) => r.compute).length;
console.log(`${ROWS.length} rows (${counted.length} exercises after de-duplication), ${numeric} with a numeric re-check`);
console.log(`answer banks: p.14 ${bank14 === ours14 ? "match" : "MISMATCH"}, p.26 ${bank26 === ours26 ? "match" : "MISMATCH"}`);
if (bad) {
  console.log(`${bad} problem(s):\n` + fails.join("\n"));
  process.exitCode = 1;
} else console.log("inventory check passed: every stated answer equals its exact re-computation (and the printed key where one exists)");

// ---------------------------------------------------------------- INVENTORY.md
const keyLabel = { official: "CML official", "answer-bank": "printed answer bank", computed: "computed (no key)" } as const;
const lines: string[] = ["# Exercise inventory", "", `${counted.length} exercises: ${ROWS.filter((r) => r.src === "CML" && r.status !== "duplicate").length} CML, ${ROWS.filter((r) => r.src === "iReady").length} i-Ready, Generated by \`npm run inventory\`.`, ""];
const clusterCounts = Object.entries(CLUSTERS).map(([k, v]) => `${v.name}: ${counted.filter((r) => r.cluster === k).length}`);
lines.push(`By cluster: ${clusterCounts.join(" · ")}`, "");
const domainCounts = Object.entries(DOMAINS).map(([k, v]) => `${v}: ${counted.filter((r) => r.domain === k).length}`);
lines.push(`By domain: ${domainCounts.join(" · ")}`, "");
for (const src of ["CML", "iReady"] as const) {
  lines.push(`## ${src === "iReady" ? "i-Ready Grade 6 At-Home Activity Packet" : "CML sample papers"}`, "");
  lines.push("| id | source | problem | domain | skill | section | diagram | input | answer | answer from | status |", "|---|---|---|---|---|---|---|---|---|---|---|");
  for (const r of ROWS.filter((x) => x.src === src)) {
    const esc = (s: string) => s.replace(/\|/g, "\\|");
    lines.push(`| ${r.id} | ${r.ref} | ${esc(r.summary)} | ${DOMAINS[r.domain]} | ${r.skill} | ${CLUSTERS[r.cluster].name} | ${(r as any).diagram ?? ""} | ${r.input} | ${esc(r.stated)} | ${keyLabel[r.key]} | ${r.status}${r.note ? ` (note)` : ""} |`);
  }
  lines.push("");
}
lines.push("## Notes and uncertain transcriptions", "");
for (const r of ROWS.filter((x) => x.note)) lines.push(`- **${r.id}** (${r.ref}): ${r.note}`);
writeFileSync(new URL("../INVENTORY.md", import.meta.url), lines.join("\n") + "\n");
console.log("wrote INVENTORY.md");
